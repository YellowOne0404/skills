MARKER = "Generated by stm32-cmake-devkit"
SKIP_DIRS = {
    ".git", ".vscode", ".idea", "build", "MDK-ARM", "EWARM", "cmake-build-debug",
    "cmake-build-release", "DSP", "NN", "RTOS", "RTOS2",
}
PORT_DIRS = {
    "m0": {"arm_cm0"},
    "m0plus": {"arm_cm0"},
    "m3": {"arm_cm3"},
    "m4": {"arm_cm4f"},
    "m4soft": {"arm_cm4"},
    "m7": {"arm_cm7"},
    "m33": {"arm_cm33_ntz", "arm_cm33"},
}
DEFINE_COMMENT = re.compile(
    r"/\*\s*#\s*define\s+(STM32[A-Za-z0-9_]+)\s*\*/\s*/\*!<\s*(.*?)\*/",
    re.S,
)


def _configure_stdio() -> None:
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8", errors="replace")


def emit(payload: dict, as_json: bool, code: int) -> int:
    if as_json:
        json.dump(payload, sys.stdout, ensure_ascii=False, indent=2)
        sys.stdout.write("\n")
    else:
        print(payload.get("summary", ""))
        details = payload.get("details") or {}
        for warning in details.get("warnings") or []:
            print(f"  warning: {warning}")
        for error in details.get("errors") or []:
            print(f"  error: {error}")
        for item in details.get("files_written") or []:
            print(f"  wrote: {item}")
    return code


def cmake_identifier(name: str) -> str:
    cleaned = re.sub(r"[^A-Za-z0-9_]", "_", name.strip()) or "firmware"
    if cleaned[0].isdigit():
        cleaned = "fw_" + cleaned
    return cleaned


def mcu_flags(device: str, cpu_text: str = "") -> tuple[str, str]:
    blob = f"{device} {cpu_text}".upper()
    dev = device.upper()
    if "CORTEX-M33" in blob or dev.startswith(("STM32H5", "STM32U5", "STM32L5", "STM32WBA")):
        return "m33", "-mcpu=cortex-m33 -mthumb -mfpu=fpv5-sp-d16 -mfloat-abi=hard"
    if "CORTEX-M7" in blob or dev.startswith(("STM32H7", "STM32F7")):
        # F76x/F77x have a double-precision FPU. Other F7 parts are single-precision.
        if dev.startswith("STM32F7") and not re.match(r"STM32F7[67]", dev):
            return "m7", "-mcpu=cortex-m7 -mthumb -mfpu=fpv5-sp-d16 -mfloat-abi=hard"
        return "m7", "-mcpu=cortex-m7 -mthumb -mfpu=fpv5-d16 -mfloat-abi=hard"
    if "CORTEX-M4" in blob or dev.startswith(("STM32F3", "STM32F4", "STM32G4", "STM32L4", "STM32WB", "STM32WL")):
        if cpu_text and "FPU" not in cpu_text.upper():
            return "m4soft", "-mcpu=cortex-m4 -mthumb -mfloat-abi=soft"
        return "m4", "-mcpu=cortex-m4 -mthumb -mfpu=fpv4-sp-d16 -mfloat-abi=hard"
    if "CORTEX-M3" in blob or dev.startswith(("STM32F1", "STM32F2", "STM32L1")):
        return "m3", "-mcpu=cortex-m3 -mthumb -mfloat-abi=soft"
    if dev.startswith(("STM32G0", "STM32L0", "STM32C0", "STM32U0")) or "M0PLUS" in blob or "M0+" in blob:
        return "m0plus", "-mcpu=cortex-m0plus -mthumb -mfloat-abi=soft"
    if "CORTEX-M0" in blob or dev.startswith("STM32F0"):
        return "m0", "-mcpu=cortex-m0 -mthumb -mfloat-abi=soft"
    raise ValueError(f"无法从 {device} 判断 Cortex-M 内核")


def core_warnings(device: str) -> list[str]:
    if re.match(r"STM32H7(45|47|55|57)", device.upper()):
        return ["双核 H7。当前按 Cortex-M7 生成。CM4 需要单独的启动文件、链接脚本和宏 CORE_CM4"]
    return []


def syscall_warning(sources: list[Path]) -> str | None:
    """Keil 常用 fputc 重定向 printf，GCC nano 走 _write / __io_putchar。"""
    has_fputc = False
    has_write = False
    for path in sources:
        if path.suffix.lower() not in {".c", ".cc", ".cpp"}:
            continue
        try:
            text = path.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        if re.search(r"\bfputc\s*\(", text):
            has_fputc = True
        if re.search(r"\b(_write|__io_putchar)\s*\(", text):
            has_write = True
    if has_fputc and not has_write:
        return "源码用 fputc 重定向 printf。GCC nano 需要 _write 或 __io_putchar，否则串口 printf 没有输出"
    return None


def is_gcc_asm(path: Path) -> bool:
    try:
        text = path.read_text(encoding="utf-8", errors="replace")[:8000]
    except OSError:
        return False
    if re.search(r"(?m)^\s*AREA\b", text):
        return False
    return any(token in text for token in (".syntax", ".section", ".thumb_func", "g_pfnVectors"))


def _skip_walk(dirnames: list[str]) -> None:
    dirnames[:] = [name for name in dirnames if name not in SKIP_DIRS and not name.startswith(".")]


def rel_posix(root: Path, path: Path) -> str:
    try:
        return path.resolve().relative_to(root.resolve()).as_posix()
    except ValueError:
        return path.resolve().as_posix()


def cmake_ownership(root: Path) -> str:
    cmake_lists = root / "CMakeLists.txt"
    if not cmake_lists.is_file():
        return "absent"
    text = cmake_lists.read_text(encoding="utf-8", errors="replace")
    return "generated" if MARKER in text else "handwritten"


def find_inputs(root: Path) -> tuple[list[Path], list[Path]]:
    """查找工程文件。Keil 工程通常在 MDK-ARM/，这里不能跳过该目录。"""
    keil: list[Path] = []
    ioc: list[Path] = []
    skip = {".git", "build", ".vscode", ".idea", "cmake-build-debug", "cmake-build-release"}
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [name for name in dirnames if name not in skip and not name.startswith(".")]
        for filename in filenames:
            path = Path(dirpath) / filename
            lower = filename.lower()
            if lower.endswith((".uvprojx", ".uvproj")):
                keil.append(path)
            elif lower.endswith(".ioc"):
                ioc.append(path)
    return keil, ioc


def _child_text(node: ET.Element | None, path: str) -> str:
    if node is None:
        return ""
    found = node.find(path)
    if found is None or found.text is None:
        return ""
    return found.text.strip()


def parse_uvprojx(path: Path, target_name: str) -> dict:
    tree = ET.parse(path)
    targets = tree.getroot().findall("./Targets/Target")
    if not targets:
        raise ValueError(f"{path} 里没有 Target")
    names = [_child_text(item, "TargetName") or f"target{index}" for index, item in enumerate(targets)]
    chosen = None
    for item, name in zip(targets, names):
        if target_name and name == target_name:
            chosen = item
            break
    if target_name and chosen is None:
        raise ValueError(f"找不到 Keil Target {target_name}。可选: {', '.join(names)}")
    if chosen is None:
        chosen = targets[0]
    common = chosen.find("./TargetOption/TargetCommonOption")
    controls = chosen.find("./TargetOption/TargetArmAds/Cads/VariousControls")
    scatter = _child_text(chosen.find("./TargetOption/TargetArmAds/LDads"), "ScatterFile")
    defines = []
    raw_defines = _child_text(controls, "Define")
    for item in raw_defines.split(","):
        item = item.strip()
        if item:
            defines.append(item)
    includes = []
    raw_includes = _child_text(controls, "IncludePath")
    for item in raw_includes.split(";"):
        item = item.strip()
        if item:
            includes.append(item)
    files = []
    for file_node in chosen.findall("./Groups/Group/Files/File"):
        include = file_node.find("./FileOption/CommonProperty/IncludeInBuild")
        if include is not None and (include.text or "").strip() == "0":
            continue
        file_path = _child_text(file_node, "FilePath")
        if file_path:
            files.append(file_path)
    return {
        "name": _child_text(chosen, "TargetName") or path.stem,
        "device": _child_text(common, "Device"),
        "cpu": _child_text(common, "Cpu"),
        "defines": defines,
        "includes": includes,
        "files": files,
        "scatter": scatter,
        "base": path.parent,
        "target_names": names,
    }


def parse_ioc(path: Path) -> dict:
    values: dict[str, str] = {}
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        values[key.strip()] = value.strip()
    return {
        "name": values.get("ProjectManager.ProjectName") or path.stem,
        "device": values.get("Mcu.Name") or values.get("Mcu.CPN") or "",
        "family": values.get("Mcu.Family") or "",
        "cpn": values.get("Mcu.CPN") or "",
    }


def device_macro(root: Path, device: str) -> str:
    short = re.sub(r"[A-Z]X$", "", device.upper())
    best_len = 0
    best = ""
    seen = 0
    for dirpath, dirnames, filenames in os.walk(root):
        _skip_walk(dirnames)
        for filename in filenames:
            if not re.fullmatch(r"stm32[a-z0-9]+xx\.h", filename, flags=re.I):
                continue
            text = (Path(dirpath) / filename).read_text(encoding="utf-8", errors="replace")
            seen += 1
            for macro, parts in DEFINE_COMMENT.findall(text):
                for token in re.findall(r"STM32[A-Z0-9]+", parts.upper()):
                    if short.startswith(token) or device.upper().startswith(token):
                        if len(token) > best_len:
                            best_len = len(token)
                            best = macro
            if seen >= 6:
                return best
    if best:
        return best
    stem = re.match(r"(STM32[A-Z]\d+)", short)
    return (stem.group(1) + "xx") if stem else ""


def parse_memory_text(text: str) -> tuple[int, int, int, int] | None:
    pattern = re.compile(
        r"\b((?:ER_|LR_)?IROM\d*|RW_IRAM\d*|IRAM\d*)\s*(?:\(|\s+)(?:UNINIT\s+)?(0x[0-9A-Fa-f]+)\s*(?:,|\s+)(?:UNINIT\s+|ALIGN\s+\d+\s+)?(0x[0-9A-Fa-f]+|\d+)",
        re.I,
    )
    flash = None
    rams: list[tuple[int, int]] = []
    for name, origin, length in pattern.findall(text):
        org = int(origin, 16)
        size = int(length, 16) if length.lower().startswith("0x") else int(length, 10)
        upper = name.upper()
        if "IROM" in upper:
            if upper.startswith("ER_") or flash is None:
                flash = (org, size)
        elif "IRAM" in upper:
            rams.append((org, size))
    if not flash or not rams:
        return None
    ram = max(rams, key=lambda item: item[1])
    return flash[0], flash[1], ram[0], ram[1]


def render_ld(flash_origin: int, flash_len: int, ram_origin: int, ram_len: int) -> str:
    return f"""/* {MARKER}. Confirm FLASH and RAM before trusting this script. */
ENTRY(Reset_Handler)
_estack = ORIGIN(RAM) + LENGTH(RAM);
_Min_Heap_Size = 0x400;
_Min_Stack_Size = 0x800;

MEMORY
{{
  FLASH (rx)  : ORIGIN = {flash_origin:#010x}, LENGTH = {flash_len:#x}
  RAM (xrw)   : ORIGIN = {ram_origin:#010x}, LENGTH = {ram_len:#x}
}}

SECTIONS
{{
  .isr_vector :
  {{
    . = ALIGN(4);
    KEEP(*(.isr_vector))
    . = ALIGN(4);
  }} >FLASH

  .text :
  {{
    . = ALIGN(4);
    *(.text)
    *(.text*)
    KEEP(*(.init))
    KEEP(*(.fini))
    . = ALIGN(4);
    _etext = .;
  }} >FLASH

  .rodata :
  {{
    . = ALIGN(4);
    *(.rodata)
    *(.rodata*)
    . = ALIGN(4);
  }} >FLASH

  .data :
  {{
    . = ALIGN(4);
    _sdata = .;
    *(.data)
    *(.data*)
    . = ALIGN(4);
    _edata = .;
  }} >RAM AT> FLASH

  _sidata = LOADADDR(.data);

  .bss :
  {{
    . = ALIGN(4);
    _sbss = .;
    *(.bss)
    *(.bss*)
    *(COMMON)
    . = ALIGN(4);
    _ebss = .;
  }} >RAM

  ._user_heap_stack :
  {{
    . = ALIGN(8);
    PROVIDE(end = .);
    PROVIDE(_end = .);
    . = . + _Min_Heap_Size;
    . = . + _Min_Stack_Size;
    . = ALIGN(8);
  }} >RAM
}}
"""


def resolve_keil_path(base: Path, raw: str) -> Path | None:
    cleaned = raw.strip().strip('"').replace("\\", "/")
    if not cleaned or "$$" in cleaned:
        return None
    path = Path(cleaned)
    if not path.is_absolute():
        path = base / path
    return path.resolve()


def _rank_named(path: Path, device: str) -> tuple:
    match = re.match(r"STM32[A-Z]\d+", device, flags=re.I)
    token = match.group(0).lower() if match else ""
    name = path.name.lower()
    in_gcc = "gcc" in [part.lower() for part in path.parts]
    return (0 if token and token in name else 1, 0 if in_gcc else 1, 0 if "flash" in name else 1, len(name))


def accept_scanned_source(path: Path, core: str) -> bool:
    name = path.name.lower()
    if name.endswith("_template.c") or name.endswith("_template.s"):
        return False
    parts = [part.lower() for part in path.parts]
    joined = "/".join(parts)
    if "/templates/arm/" in joined or "/templates/iar/" in joined:
        return False
    if path.suffix.lower() in {".s", ".asm"} and not is_gcc_asm(path):
        return False
    if "portable" in parts:
        if "memmang" in parts:
            return name == "heap_4.c"
        if any(part in parts for part in ("iar", "rvds", "tasking")):
            return False
        if "gcc" in parts:
            return any(part in PORT_DIRS[core] for part in parts)
        return False
    return path.suffix.lower() in {".c", ".cc", ".cpp", ".s", ".sx"}


def prefer_one(paths: list[Path], prefix: str, device: str) -> list[Path]:
    group = [path for path in paths if path.name.lower().startswith(prefix)]
    if len(group) <= 1:
        return paths
    group.sort(key=lambda path: _rank_named(path, device))
    keep = group[0].resolve()
    drop = {path.resolve() for path in group[1:]}
    # 同名 system/startup 优先留在 Core，避免 Templates 再编一份。
    core_copies = [path for path in group if "core" in [part.lower() for part in path.parts]]
    if core_copies:
        core_copies.sort(key=lambda path: _rank_named(path, device))
        keep = core_copies[0].resolve()
        drop = {path.resolve() for path in group if path.resolve() != keep}
    return [path for path in paths if path.resolve() not in drop]


def collect_includes(root: Path, sources: list[Path]) -> list[Path]:
    found: list[Path] = []
    seen: set[Path] = set()

    def add(path: Path) -> None:
        if not path.is_dir():
            return
        resolved = path.resolve()
        if resolved in seen:
            return
        parts = [part.lower() for part in resolved.parts]
        if any(part in parts for part in ("iar", "rvds", "tasking")):
            return
        seen.add(resolved)
        found.append(resolved)

    for dirpath, dirnames, _filenames in os.walk(root):
        _skip_walk(dirnames)
        base = Path(dirpath)
        if base.name.lower() in {"inc", "include"}:
            add(base)
    for source in sources:
        if source.name == "port.c":
            add(source.parent)
        if source.name.lower() == "tasks.c":
            add(source.parent / "include")
    return found


def scan_ioc_sources(root: Path, device: str, core: str) -> tuple[list[Path], list[str]]:
    warnings: list[str] = []
    sources: list[Path] = []
    for dirpath, dirnames, filenames in os.walk(root):
        _skip_walk(dirnames)
        for filename in filenames:
            path = Path(dirpath) / filename
            if path.suffix.lower() not in {".c", ".cc", ".cpp", ".s", ".sx", ".asm"}:
                continue
            if accept_scanned_source(path, core):
                sources.append(path)
    if not any(path.suffix.lower() == ".c" for path in sources):
        raise ValueError("没有可编译的 C 源码。CubeMX 需要先 Generate Code，生成 Core/ 后再转换")
    sources = prefer_one(sources, "startup_", device)
    sources = prefer_one(sources, "system_stm32", device)
    startups = [path for path in sources if path.name.lower().startswith("startup_")]
    if not startups:
        warnings.append("没有 GCC 启动文件 startup_*.s。Keil 的 ARMASM 启动文件不能交给 arm-none-eabi-gcc")
    return sources, warnings


def model_from_keil(root: Path, info: dict) -> dict:
    if not info["device"]:
        raise ValueError("Keil 工程没有 Device")
    core, flags = mcu_flags(info["device"], info["cpu"])
    warnings: list[str] = []
    if len(info["target_names"]) > 1:
        warnings.append("多个 Keil Target，使用 " + info["name"] + "。其他: " + ", ".join(info["target_names"]))
    sources: list[Path] = []
    for raw in info["files"]:
        path = resolve_keil_path(info["base"], raw)
        if path is None:
            warnings.append(f"跳过 Keil 宏路径: {raw}")
            continue
        if not path.is_file():
            warnings.append(f"源文件不存在: {raw}")
            continue
        if path.suffix.lower() in {".h", ".hpp", ".inc", ".txt", ".sct"}:
            continue
        if path.suffix.lower() in {".s", ".asm", ".sx"} and not is_gcc_asm(path):
            warnings.append(f"跳过 ARMASM 文件: {path.name}")
            continue
        if path.suffix.lower() in {".c", ".cc", ".cpp", ".s", ".sx", ".a", ".lib"}:
            sources.append(path)
    gcc_startups = [path for path in sources if path.name.lower().startswith("startup_") and is_gcc_asm(path)]
    if not gcc_startups:
        discovered, scan_warnings = scan_ioc_sources(root, info["device"], core)
        warnings.extend(scan_warnings)
        extra = [path for path in discovered if path.name.lower().startswith("startup_") or path.name.lower().startswith("system_stm32")]
        known = {path.resolve() for path in sources}
        for path in extra:
            if path.resolve() not in known:
                sources.append(path)
                warnings.append(f"改用 GCC 启动/系统文件: {path.name}")
    includes = []
    for raw in info["includes"]:
        path = resolve_keil_path(info["base"], raw)
        if path is None:
            warnings.append(f"跳过 include 宏: {raw}")
            continue
        if path.is_dir():
            includes.append(path)
        else:
            warnings.append(f"include 目录不存在: {raw}")
    return {
        "name": info["name"],
        "device": info["device"],
        "core": core,
        "flags": flags,
        "defines": info["defines"],
        "includes": includes,
        "sources": sources,
        "scatter": resolve_keil_path(info["base"], info["scatter"]) if info["scatter"] else None,
        "cpu": info["cpu"],
        "warnings": warnings + core_warnings(info["device"]) + ([note] if (note := syscall_warning(sources)) else []),
        "origin": "keil",
    }


def model_from_ioc(root: Path, info: dict) -> dict:
    if not info["device"]:
        raise ValueError(f"ioc 里没有 Mcu.Name")
    core, flags = mcu_flags(info["device"])
    sources, warnings = scan_ioc_sources(root, info["device"], core)
    macro = device_macro(root, info["device"])
    defines = ["USE_HAL_DRIVER"]
    if macro:
        defines.append(macro)
    else:
        warnings.append("没有在 stm32xxxx.h 里匹配到器件宏，需要手工补 -DSTM32xxxx")
    if not any("hal" in part.lower() for path in sources for part in path.parts):
        defines = [item for item in defines if item != "USE_HAL_DRIVER"]
    return {
        "name": info["name"],
        "device": info["device"],
        "core": core,
        "flags": flags,
        "defines": defines,
        "includes": collect_includes(root, sources),
        "sources": sources,
        "scatter": None,
        "cpu": "",
        "warnings": warnings + core_warnings(info["device"]) + ([note] if (note := syscall_warning(sources)) else []),
        "origin": "cubemx",
    }


def attach_linker(root: Path, model: dict) -> str | None:
    scripts: list[Path] = []
    for dirpath, dirnames, filenames in os.walk(root):
        _skip_walk(dirnames)
        for filename in filenames:
            if filename.endswith(".ld"):
                scripts.append(Path(dirpath) / filename)
    if scripts:
        scripts.sort(key=lambda path: _rank_named(path, model["device"]))
        model["linker"] = scripts[0]
        model["linker_text"] = None
        if len(scripts) > 1:
            model["warnings"].append(f"有多个链接脚本，使用 {scripts[0].name}")
        return None
    memory = None
    scatter = model.get("scatter")
    if isinstance(scatter, Path) and scatter.is_file():
        memory = parse_memory_text(scatter.read_text(encoding="utf-8", errors="replace"))
    if memory is None and model.get("cpu"):
        memory = parse_memory_text(model["cpu"])
    if memory is None:
        return "没有 .ld，Keil scatter/Cpu 里也没有可用的 Flash/RAM 地址"
    origin, length, ram_origin, ram_length = memory
    model["linker"] = root / "cmake" / "generated_flash.ld"
    model["linker_text"] = render_ld(origin, length, ram_origin, ram_length)
    model["warnings"].append(
        f"链接脚本由 Keil 存储区生成: FLASH {origin:#x}+{length:#x}, RAM {ram_origin:#x}+{ram_length:#x}。下载前请核对"
    )
    return None


def has_syscalls(sources: list[Path]) -> bool:
    names = {path.name.lower() for path in sources}
    return bool(names & {"syscalls.c", "sysmem.c", "_sbrk.c"}) or any(name.startswith("syscalls") for name in names)


