def main(argv: list[str] | None = None) -> int:
    _configure_stdio()
    parser = argparse.ArgumentParser(description="把 Keil 或 CubeMX 工程转成 CMake")
    parser.add_argument("--project", default=".")
    parser.add_argument("--file", default="", help="指定 .uvprojx/.uvproj/.ioc")
    parser.add_argument("--target", default="", help="Keil Target 名称")
    parser.add_argument("--force", action="store_true", help="覆盖已有 CMakeLists.txt，原文件备份为 .bak")
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--configure", action="store_true")
    parser.add_argument("--build", action="store_true")
    parser.add_argument("--preset", default="Debug")
    parser.add_argument("--product-id", default="", help="多产品仓库的 hbuild 序号")
    parser.add_argument("--json", action="store_true")
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args(argv)
    if args.self_test:
        return self_test()
    root = Path(args.project).resolve()
    source = Path(args.file).resolve() if args.file else None
    try:
        payload, code = migrate(
            root,
            source,
            args.target,
            args.force,
            args.dry_run,
            args.configure or args.build,
            args.build,
            args.preset,
            args.product_id,
        )
    except (ValueError, RuntimeError, ET.ParseError) as exc:
        payload = {
            "status": "error",
            "action": "migrate",
            "summary": str(exc),
            "details": {"project": str(root)},
        }
        code = 1
    return emit(payload, args.json, code)


if __name__ == "__main__":
    sys.exit(main())
